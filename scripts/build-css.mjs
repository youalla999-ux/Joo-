// Concatenates src/css/*.css (in filename order) into public/assets/css/style.css, with a light minify.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "src/css");
const files = readdirSync(dir).filter((f) => f.endsWith(".css")).sort();
const min = process.argv.includes("--min");
let out = `/* Joo Store stylesheet — generated by scripts/build-css.mjs from src/css/*. Do not edit by hand. */\n`;
for (const f of files) {
  let css = readFileSync(join(dir, f), "utf8");
  if (min) css = css.replace(/\/\*[\s\S]*?\*\//g, "").replace(/\s*\n\s*/g, "\n").replace(/\s*([{};,>])\s*/g, "$1").replace(/;}/g, "}");
  else css = `/* --- ${f} --- */\n${css}`;
  out += css + "\n";
}
writeFileSync(join(root, "public/assets/css/style.css"), out);
console.log(`style.css built from ${files.length} files (${(out.length / 1024).toFixed(1)} KB)`);
